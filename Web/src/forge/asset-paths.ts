import modelContentAliases from './model-content-aliases.generated.json' with {type: 'json'};

/** Published website files. Source assets and backups never belong in these URLs. */
export const assetPaths = {
    models: 'assets/models',
    textures: 'assets/textures',
    audio: 'assets/audio',
    animations: 'assets/animations',
    poses: 'assets/poses',
    thumbnails: 'assets/thumbnails',
    vendor: 'assets/vendor',
    downloads: 'assets/downloads',
    imports: 'assets/imports',
    pixel: 'assets/pixel',
    catalogs: 'data/catalogs',
    maps: 'data/maps',
    workshop: 'data/workshop'
} as const;

/** The one published name of a recording: its Opus payload hash under `assets/audio/content/`. `Tools/Audio/content_publication.py` writes the same name. */
export const audioContentFile = (contentHash: string) => `${assetPaths.audio}/content/${contentHash}.ogg`;

/** The two published model levels. */
export const modelLevels = ['low', 'original'] as const;
export type ModelLevel = (typeof modelLevels)[number];

/** Model IDs whose published bytes are identical to another model's: each keeps its own ID, catalog row, source and
 *  licence, and is served from that model's single physical file. Generated by `asset-dedup.ts --aliases`; the
 *  publication check reads every aliased row's revision from the shared file, so an alias whose content diverged fails it. */
const contentAliases: Readonly<Record<string, string>> = modelContentAliases.aliases;

/** A model ID is `<family>-low` or `<family>-original`; the suffix names the file this ID would own. */
export function modelStorageFile(id: string): string {
    const match = /^([a-zA-Z0-9][a-zA-Z0-9_-]*)-(original|low)$/.exec(id);
    if (!match) throw new Error(`Invalid model ID: ${id}`);
    return `${assetPaths.models}/${match[1]}/${match[2]}.glb`;
}
/** The file a model is read and served from: its own, or the one it shares content with. */
export function modelFile(id: string): string {
    modelStorageFile(id);
    return modelStorageFile(contentAliases[id] ?? id);
}
