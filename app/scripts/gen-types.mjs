// Generates src/renderer/generated/skin-document.ts from the backend `schema` method.
// Usage: pnpm gen:types            (asks the backend)
//        pnpm gen:types --from x.json  (uses a schema file the backend wrote)
import { spawn } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const appDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(appDir, '..');
const out = join(appDir, 'src/renderer/generated/skin-document.ts');

function askBackend() {
  const exe = ['Debug', 'Release']
    .flatMap((c) => ['', 'win-x64/'].map((rid) => join(repo, `src/SkinForge.Backend/bin/${c}/net10.0/${rid}SkinForge.Backend.exe`)))
    .find(existsSync);
  const dataDir = join(appDir, 'GTFO_UserData');
  const child = exe
    ? spawn(exe, ['--data-dir', dataDir])
    : spawn('dotnet', ['run', '--project', join(repo, 'src/SkinForge.Backend'), '--', '--data-dir', dataDir]);
  return new Promise((resolve, reject) => {
    let buf = '';
    child.stdout.setEncoding('utf8').on('data', (d) => {
      buf += d;
      for (let i; (i = buf.indexOf('\n')) >= 0; ) {
        const line = buf.slice(0, i);
        buf = buf.slice(i + 1);
        let msg;
        try { msg = JSON.parse(line); } catch { continue; }
        if (msg.id !== 1) continue;
        child.kill();
        msg.error ? reject(new Error(msg.error.message)) : resolve(msg.result);
      }
    });
    child.on('error', reject);
    child.on('exit', (code) => reject(new Error(`backend exited (${code}) before answering schema`)));
    child.stdin.write(JSON.stringify({ id: 1, method: 'schema', params: {} }) + '\n');
  });
}

const fromIdx = process.argv.indexOf('--from');
const schema = fromIdx > 0 ? JSON.parse(readFileSync(process.argv[fromIdx + 1], 'utf8')) : await askBackend();
const ts = await compile(typeof schema === 'string' ? JSON.parse(schema) : schema, 'SkinDocument', {
  bannerComment: '// Generated by scripts/gen-types.mjs from the backend `schema` method. Do not edit.',
  additionalProperties: false,
  strictIndexSignatures: false,
  format: false,
});
writeFileSync(out, ts);
console.log(`wrote ${out}`);
