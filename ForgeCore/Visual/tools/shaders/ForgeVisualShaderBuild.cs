#if UNITY_EDITOR
using System;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using UnityEditor;
using UnityEngine;

/// <summary>Builds ForgeVisual's shaders (particle, marker, outline, procedural, the toon shader's three entries and the lit cut-out) into one small bundle with Unity 2019.4.21f1, writes it to ForgeCore's Assets/Shaders
/// (embedded in ForgeCore.dll) and its reader (Native/ShaderBundle.Generated.cs). Run by build_shaders.ps1 through ForgeCore's UnityBatch with FORGE_TOOLS (this folder) and FORGE_NATIVE (the Native folder).
/// The procedural shader includes the drawing programs (ForgeFxPrograms.hlsl) and a dispatch made here from the program catalogue (Data/fx-programs.json):
/// program i is the catalogue's i-th entry, its function fx_&lt;name&gt;. The toon entries include ForgeToon.hlsl. The source hash covers what reaches the shaders:
/// the shaders, the toon include, the programs and the catalogue's program names in order (not its version, labels or defaults).</summary>
public static class ForgeVisualShaderBuild
{
    const string BundleName = "forgevisual-shaders";
    static readonly string[] Sources = { "ForgeVisualParticle.shader", "ForgeVisualMarker.shader", "ForgeVisualOutline.shader", "ForgeVisualProcedural.shader",
        "ForgeVisualToonForward.shader", "ForgeVisualToonDeferred.shader", "ForgeVisualToonOverlay.shader", "ForgeVisualLitCutout.shader" };
    const string Programs = "ForgeFxPrograms.hlsl", Dispatch = "ForgeFxDispatch.hlsl", Catalogue = "../../Data/fx-programs.json", Toon = "ForgeToon.hlsl";

    [Serializable] class CatalogueFile { public CatalogueProgram[] programs = Array.Empty<CatalogueProgram>(); }
    [Serializable] class CatalogueProgram { public string name = ""; }

    /// <summary>`fx_dispatch(program, input)`: one branch per catalogue program, in catalogue order.</summary>
    static string DispatchSource(string[] names)
    {
        var text = new StringBuilder("// Generated by ForgeVisualShaderBuild.cs from Data/fx-programs.json; program i is the catalogue's i-th entry.\n#define FX_PROGRAM_COUNT ")
            .Append(names.Length).Append("\nfloat4 fx_dispatch(int program, FxIn i)\n{\n    float4 c = float4(0.0, 0.0, 0.0, 0.0);\n");
        for (var i = 0; i < names.Length; i++)
            text.Append(i == 0 ? "    if" : "    else if").Append(" (program == ").Append(i).Append(") c = fx_").Append(names[i]).Append("(i);\n");
        return text.Append("    return c;\n}\n").ToString();
    }

    public static void Build() => UnityBatch.Run(Run);

    static void Run()
    {
        var tools = UnityBatch.Env("FORGE_TOOLS");
        var native = UnityBatch.Env("FORGE_NATIVE");
        var project = UnityBatch.Project;
        var assets = new string[Sources.Length];
        var all = new StringBuilder();
        for (var i = 0; i < Sources.Length; i++)
        {
            var source = Path.Combine(tools, Sources[i]);
            assets[i] = "Assets/" + Sources[i];
            File.Copy(source, Path.Combine(project, assets[i]), true);
            all.Append(File.ReadAllText(source).Replace("\r\n", "\n"));
        }
        var toon = File.ReadAllText(Path.Combine(tools, Toon)).Replace("\r\n", "\n");
        var programs = File.ReadAllText(Path.Combine(tools, Programs)).Replace("\r\n", "\n");
        var catalogue = JsonUtility.FromJson<CatalogueFile>(File.ReadAllText(Path.Combine(tools, Catalogue)));
        if (catalogue == null || catalogue.programs == null || catalogue.programs.Length == 0) throw new InvalidOperationException("The program catalogue lists no programs.");
        var names = catalogue.programs.Select(p => p.name).ToArray();
        all.Append(toon).Append(programs).Append(string.Join("\n", names));
        File.WriteAllText(Path.Combine(project, "Assets", Toon), toon);
        File.WriteAllText(Path.Combine(project, "Assets", Programs), programs);
        File.WriteAllText(Path.Combine(project, "Assets", Dispatch), DispatchSource(names));
        AssetDatabase.Refresh(ImportAssetOptions.ForceSynchronousImport);
        foreach (var asset in assets)
        {
            AssetDatabase.ImportAsset(asset, ImportAssetOptions.ForceSynchronousImport);
            var shader = AssetDatabase.LoadAssetAtPath<Shader>(asset) ?? throw new InvalidOperationException("Unity did not import " + asset + ".");
            // Not isSupported: the batch-mode editor has no graphics device, and on it a shader with only a deferred pass counts as unsupported.
            if (ShaderUtil.ShaderHasError(shader)) throw new InvalidOperationException(asset + " has compile errors.");
        }
        var output = Path.Combine(project, "shader-out");
        Directory.CreateDirectory(output);
        var result = BuildPipeline.BuildAssetBundles(output, new[] { new AssetBundleBuild { assetBundleName = BundleName, assetNames = assets } },
            BuildAssetBundleOptions.ForceRebuildAssetBundle | BuildAssetBundleOptions.DeterministicAssetBundle, BuildTarget.StandaloneWindows64);
        if (result == null) throw new InvalidOperationException("The shader bundle build failed.");
        var bytes = File.ReadAllBytes(Path.Combine(output, BundleName));
        string sha;
        using (var hash = SHA256.Create()) sha = BitConverter.ToString(hash.ComputeHash(Encoding.UTF8.GetBytes(all.ToString()))).Replace("-", "").ToLowerInvariant();
        File.WriteAllBytes(Path.GetFullPath(Path.Combine(native, "../../Assets/Shaders", BundleName + ".shaderbundle")), bytes);
        File.WriteAllText(Path.Combine(native, "ShaderBundle.Generated.cs"),
            "// Generated from tools/shaders/*.shader with Unity 2019.4.21f1 by tools/shaders/build_shaders.ps1; do not edit.\nnamespace ForgeVisual;\n\n"
            + "internal static class ShaderBundle\n{\n    internal const string SourceSha256 = \"" + sha + "\";\n"
            + "    internal const string ParticleAsset = \"" + assets[0] + "\";\n    internal const string MarkerAsset = \"" + assets[1] + "\";\n"
            + "    internal const string OutlineAsset = \"" + assets[2] + "\";\n    internal const string ProceduralAsset = \"" + assets[3] + "\";\n"
            + "    internal const string ToonForwardAsset = \"" + assets[4] + "\";\n    internal const string ToonDeferredAsset = \"" + assets[5] + "\";\n"
            + "    internal const string ToonOverlayAsset = \"" + assets[6] + "\";\n    internal const string LitCutoutAsset = \"" + assets[7] + "\";\n"
            + "    internal static byte[] Read() => ForgeCore.Assets.Embedded(\"ForgeCore.Shaders." + BundleName + ".shaderbundle\");\n}\n");
        Debug.Log("SHADER_BUILT " + bytes.Length + " bytes " + sha);
    }
}
#endif
